fn rust_sources(directory: &Path, output: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(directory)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            rust_sources(&path, output)?;
        } else if path.extension().is_some_and(|extension| extension == "rs") {
            output.push(path);
        }
    }
    Ok(())
}

pub fn verify(expected_root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let compiled_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize()?;
    let root = expected_root.canonicalize()?;
    if root != compiled_root {
        return Err("stale editor acceptance executable: compiled workspace differs from the integration launcher's workspace".into());
    }
    let mut actual: Vec<PathBuf> = FIXED_SOURCES.iter().map(|relative| root.join(relative)).collect();
    for relative in SOURCE_ROOTS {
        rust_sources(&root.join(relative), &mut actual)?;
    }
    actual.sort();
    actual.dedup();
    let mut expected: Vec<PathBuf> = COMPILED_SOURCES.iter().map(|(relative, _)| root.join(relative)).collect();
    expected.sort();
    if actual != expected {
        return Err("stale editor acceptance executable: compiled source inventory differs from the current workspace".into());
    }
    for (relative, compiled) in COMPILED_SOURCES {
        let current = std::fs::read(root.join(relative))?;
        if current != *compiled {
            return Err(format!("stale editor acceptance executable: {relative} differs from its compiled source").into());
        }
    }
    println!("bounce_editor_state: current-source snapshot verified ({} files)", COMPILED_SOURCES.len());
    Ok(())
}
